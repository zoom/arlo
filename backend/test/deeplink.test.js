// "Open Arlo in Zoom": after signing in from a browser, the server asks Zoom
// for a deeplink that opens the Zoom client straight into the app. Calls to
// Zoom are stubbed; everything else is the real server.
const h = require('./helpers');

h.setTestEnv();

const test = require('node:test');
const assert = require('node:assert/strict');
const { generateToken, encryptToken, decryptToken } = require('../src/services/auth');
const { userStore, tokenStore } = require('../src/lib/memoryStore');

let srv;
test.before(async () => { srv = await h.startServer(); });
test.after(() => { srv.server.closeAllConnections?.(); srv.server.close(); global.fetch = realFetch; });

const realFetch = global.fetch;
let zoomCalls;

/** Intercept only requests to Zoom; everything else is a real request. */
function stubZoom(handlers) {
  zoomCalls = [];
  global.fetch = async (input, init = {}) => {
    const url = String(input);
    if (!/^https:\/\/(api\.)?zoom\.us\//.test(url)) return realFetch(input, init);
    const call = { url, method: init.method || 'GET', headers: init.headers || {}, body: init.body ? String(init.body) : '' };
    zoomCalls.push(call);
    const key = url.includes('/oauth/token') ? 'token' : 'deeplink';
    const { status = 200, body = {} } = await handlers[key](call);
    return new Response(JSON.stringify(body), { status, headers: { 'content-type': 'application/json' } });
  };
}
test.afterEach(() => { global.fetch = realFetch; });

let n = 0;
function signIn({ accessToken = 'access-1', refreshToken = 'refresh-1', expiresInMs = 3_600_000, withTokens = true } = {}) {
  n += 1;
  const user = userStore.upsert(`zoom-deeplink-${n}`, { email: 'x@example.test', displayName: 'X', avatarUrl: null });
  if (withTokens) {
    tokenStore.store(user.id, {
      accessToken: accessToken ? encryptToken(accessToken) : null,
      refreshToken: encryptToken(refreshToken),
      expiresAt: new Date(Date.now() + expiresInMs),
      scopes: [],
    });
  }
  const cookie = `sessionToken=${generateToken({ userId: user.id, zoomUserId: user.zoomUserId, exp: Date.now() + 60_000 })}`;
  return { user, cookie };
}
const requestDeeplink = (cookie) => h.postJson(`${srv.base}/api/auth/deeplink`, {}, cookie ? { cookie } : {});
const ZOOM_LINK = 'https://zoom.us/launch/chatapp/Zx_abc123.def456';
const MARKETPLACE_LINK = 'https://marketplace.zoom.us/zoomapp/test-client-id/context/panel/target/launch/deeplink';

test('a signed-in user gets a deeplink generated by Zoom with their own token', async () => {
  stubZoom({ deeplink: () => ({ body: { deeplink: ZOOM_LINK } }) });
  const { cookie } = signIn({ accessToken: 'access-abc' });

  const res = await requestDeeplink(cookie);
  assert.equal(res.status, 200);
  assert.deepEqual(res.body, { deeplink: ZOOM_LINK, source: 'zoom' });

  assert.equal(zoomCalls.length, 1);
  assert.equal(zoomCalls[0].url, 'https://api.zoom.us/v2/zoomapp/deeplink');
  assert.equal(zoomCalls[0].method, 'POST');
  assert.equal(zoomCalls[0].headers.Authorization, 'Bearer access-abc');
  assert.deepEqual(JSON.parse(zoomCalls[0].body), { action: 'open', type: 1 });
});

test('it requires a session', async () => {
  stubZoom({ deeplink: () => ({ body: { deeplink: ZOOM_LINK } }) });
  assert.equal((await requestDeeplink(null)).status, 401);
  assert.equal(zoomCalls.length, 0);
});

test('an expired access token is refreshed first, and the rotated tokens are kept', async () => {
  stubZoom({
    token: () => ({ body: { access_token: 'access-new', refresh_token: 'refresh-new', expires_in: 3600, scope: 'zoomapp:inmeeting' } }),
    deeplink: () => ({ body: { deeplink: ZOOM_LINK } }),
  });
  const { user, cookie } = signIn({ accessToken: null, refreshToken: 'refresh-old', expiresInMs: -1000 });

  const res = await requestDeeplink(cookie);
  assert.equal(res.body.deeplink, ZOOM_LINK);
  assert.match(zoomCalls[0].url, /\/oauth\/token$/);
  assert.match(zoomCalls[0].body, /grant_type=refresh_token/);
  assert.match(zoomCalls[0].body, /refresh_token=refresh-old/);
  assert.equal(zoomCalls[1].headers.Authorization, 'Bearer access-new');

  const stored = tokenStore.get(user.id);
  assert.equal(decryptToken(stored.accessToken), 'access-new');
  assert.equal(decryptToken(stored.refreshToken), 'refresh-new');
  assert.equal(new Date(stored.expiresAt) > new Date(), true);
});

test('when Zoom refuses (for example a missing scope) it falls back to the Marketplace launch link', async () => {
  stubZoom({ deeplink: () => ({ status: 400, body: { code: 4711, message: 'Invalid access token, does not contain scopes' } }) });
  const { cookie } = signIn();
  const res = await requestDeeplink(cookie);
  assert.equal(res.status, 200);
  assert.deepEqual(res.body, { deeplink: MARKETPLACE_LINK, source: 'marketplace' });
});

test('a link that does not point at Zoom is never passed on', async () => {
  for (const bad of ['https://evil.example/launch', 'http://zoom.us/launch/x', 'https://zoom.us.evil.example/x', 'javascript:alert(1)', 42, undefined]) {
    stubZoom({ deeplink: () => ({ body: { deeplink: bad } }) });
    const { cookie } = signIn();
    const res = await requestDeeplink(cookie);
    assert.deepEqual(res.body, { deeplink: MARKETPLACE_LINK, source: 'marketplace' }, `for ${bad}`);
  }
});

test('a user without Zoom tokens still gets the Marketplace launch link', async () => {
  stubZoom({ deeplink: () => ({ body: { deeplink: ZOOM_LINK } }) });
  const { cookie } = signIn({ withTokens: false });
  const res = await requestDeeplink(cookie);
  assert.deepEqual(res.body, { deeplink: MARKETPLACE_LINK, source: 'marketplace' });
  assert.equal(zoomCalls.length, 0);
});

test('a failed token refresh falls back instead of failing the request', async () => {
  stubZoom({ token: () => ({ status: 400, body: { reason: 'Invalid Token!' } }), deeplink: () => ({ body: { deeplink: ZOOM_LINK } }) });
  const { cookie } = signIn({ accessToken: null, expiresInMs: -1000 });
  const res = await requestDeeplink(cookie);
  assert.deepEqual(res.body, { deeplink: MARKETPLACE_LINK, source: 'marketplace' });
});

test('the deeplink and the tokens are never written to the logs', async () => {
  stubZoom({ deeplink: () => ({ body: { deeplink: ZOOM_LINK } }) });
  const { cookie } = signIn({ accessToken: 'access-secret-value' });
  const lines = [];
  const original = { log: console.log, warn: console.warn, error: console.error };
  console.log = console.warn = console.error = (...args) => lines.push(args.map(String).join(' '));
  try { await requestDeeplink(cookie); } finally { Object.assign(console, original); }
  const output = lines.join('\n');
  assert.equal(output.includes('Zx_abc123'), false);
  assert.equal(output.includes('access-secret-value'), false);
});

test('after a token refresh the restore cookie is reissued, so a later restart does not bring back a dead refresh token', async () => {
  const { openSession, RESTORE_COOKIE } = require('../src/services/sessionRestore');
  stubZoom({
    token: () => ({ body: { access_token: 'access-new', refresh_token: 'refresh-rotated', expires_in: 3600, scope: 'zoomapp:inmeeting' } }),
    deeplink: () => ({ body: { deeplink: ZOOM_LINK } }),
  });
  const { cookie } = signIn({ accessToken: null, refreshToken: 'refresh-old', expiresInMs: -1000 });
  const res = await fetch(`${srv.base}/api/auth/deeplink`, { method: 'POST', headers: { cookie } });
  const set = res.headers.getSetCookie().find((c) => c.startsWith(`${RESTORE_COOKIE}=`));
  assert.ok(set, 'restore cookie reissued');
  const value = decodeURIComponent(set.split(';')[0].slice(RESTORE_COOKIE.length + 1));
  assert.equal(openSession(value).rt, 'refresh-rotated');
});
